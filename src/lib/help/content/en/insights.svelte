<h2 class="mb-3 mt-8 text-xl font-semibold">Three tabs</h2>
<p class="mb-6">
	The <strong>Insights</strong> page is split into <strong>Nutrition</strong>,
	<strong>Weight</strong> and <strong>Sleep</strong>. Nutrition covers trends, goal adherence, a
	calendar heatmap, your logging streak, a macro radar and day-of-week patterns, plus a set of
	deeper analytics cards (nutrient timing, food diversity, meal regularity and more) you can expand
	one by one. The Weight and Sleep tabs mirror the Weight and Sleep pages, so you can review either
	from the same place.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Pinning to the dashboard</h2>
<p class="mb-6">
	Found an analytics card you check often? Tap its pin to add it to your <strong>Home</strong>
	dashboard, so it's there without opening Insights every time. You can pin up to six at once — unpin
	one from either the card or the dashboard to make room for another.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Reading a card</h2>
<p class="mb-6">
	Most cards need a run of consistent logging (and, for the weight and sleep ones, regular weigh-ins
	or sleep logs) before they say anything meaningful — a thin card with one or two days behind it is
	noise, not a pattern. Give it a couple of weeks before drawing conclusions from it.
</p>
