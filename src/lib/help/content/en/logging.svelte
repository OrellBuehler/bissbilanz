<h2 class="mb-3 mt-8 text-xl font-semibold">Adding an entry</h2>
<p class="mb-6">
	Tap <strong>Add</strong> on any meal section to open the log sheet. It has five tabs:
</p>
<ul class="mb-6 list-disc space-y-1 pl-6">
	<li><strong>Search</strong> — your own food database, by name, label or brand.</li>
	<li><strong>Favorites</strong> — foods and recipes you've starred, one tap to log.</li>
	<li><strong>Recent</strong> — whatever you logged most recently.</li>
	<li><strong>Recipes</strong> — any recipe you've built.</li>
	<li>
		<strong>Quick log</strong> — for something you don't want to save as a food, like a restaurant meal.
		Enter calories and macros directly (or just a name and estimate) and it's logged without creating
		a food.
	</li>
</ul>
<p class="mb-6">
	Whichever tab you use, you can set the number of servings and, from the top of the sheet, the time
	it was eaten before confirming.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Editing and deleting entries</h2>
<p class="mb-6">
	Tap any logged entry to change its servings, meal, date or time, or to delete it. Moving an entry
	to a different day shows an <strong>Undo</strong> option in case you tapped the wrong day.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Copying a past day</h2>
<p class="mb-6">
	Eating the same thing you did a few days ago? Open that day in <strong>History</strong>, use
	<strong>Copy from another day</strong> and pick the source date — every entry from that day is added
	to the one you're viewing (nothing is overwritten, so it's safe to use on a day that already has entries).
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Favorites</h2>
<p class="mb-6">
	Star any food or recipe to add it to <strong>Favorites</strong>, which also shows up as a
	dashboard widget for one-tap logging. In Settings you can decide whether a favorite is assigned to
	a meal by time of day, or asks you which meal each time.
</p>
