<h2 class="mb-3 mt-8 text-xl font-semibold">Set your daily goals</h2>
<p class="mb-6">
	Open <strong>Goals</strong> and set your daily calorie target, then protein, carbs and fat (fiber follows
	automatically). These are what your dashboard and history compare every day against. You can change
	them at any time — there's no lock-in.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Log your first meal</h2>
<p class="mb-6">
	On the <strong>Home</strong> dashboard, each meal section (Breakfast, Lunch, Dinner, Snacks by
	default) has an <strong>Add</strong> button. It opens a search across your food database, plus tabs
	for favorites, recently logged foods, recipes and a quick log for things you don't want to save as a
	food. Tap a result, set the servings, and it's logged.
</p>
<p class="mb-6">
	Don't have anything in your food database yet? Scan a barcode or search Open Food Facts from the
	same screen — see the scanning guide for details.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Make the dashboard yours</h2>
<p class="mb-6">
	In <strong>Settings</strong>, the <strong>Dashboard Sections</strong> card lists every widget the Home
	screen can show — the day log, the chart, favorites, recipe suggestions, supplements, weight, sleep,
	meal and top-food breakdowns, fasting and day properties (water, activity calories, notes). Toggle any
	of them off, and drag the handles to reorder the ones you keep.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Find your way around</h2>
<p class="mb-3">The sidebar (or the bottom bar on a phone) is grouped by what you're doing:</p>
<ul class="mb-6 list-disc space-y-1 pl-6">
	<li><strong>Home, Favorites, History</strong> — day-to-day logging.</li>
	<li>
		<strong>Foods, Recipes, Recipe suggestions, Supplements, Fasting, AI tasks</strong> — managing what
		you can log.
	</li>
	<li><strong>Insights, Goals, Weight, Sleep, Maintenance</strong> — reviewing trends.</li>
	<li><strong>Help, Settings</strong> — this help center, and app preferences.</li>
</ul>
