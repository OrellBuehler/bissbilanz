<h2 class="mb-3 mt-8 text-xl font-semibold">Barcode scanning</h2>
<p class="mb-6">
	Tap the scan button on the dashboard, or <strong>Scan</strong> on a day in History, to open the camera.
	Point it at a packaged product's barcode — if it's already in your food database you go straight to
	logging it; otherwise Bissbilanz looks it up on Open Food Facts and prefills a new food with its name,
	serving size and nutrition for you to check and save.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Nutrition label scanning</h2>
<p class="mb-6">
	When adding or editing a food, use <strong>Scan label</strong> to photograph the nutrition facts panel
	on the packaging instead of typing every number by hand. The scan runs entirely on your device — nothing
	is uploaded — and reads calories, macros and the extended nutrients it recognizes into the form, which
	you can review and correct before saving.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Searching Open Food Facts</h2>
<p class="mb-6">
	No barcode to scan, or the product isn't packaged? Search for it on the <strong>Foods</strong>
	page — if fewer than a handful of your own foods match, results from Open Food Facts appear below them.
	Tap one to prefill a new food the same way a barcode scan would.
</p>
<p class="mb-6">
	Either way, the values that get saved are a copy in <em>your</em> food database — see
	<a href="/help/food-database" class="underline">Your food database</a> for why, and how to fix a value
	that's wrong.
</p>
