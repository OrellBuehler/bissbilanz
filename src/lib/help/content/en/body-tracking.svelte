<h2 class="mb-3 mt-8 text-xl font-semibold">Weight</h2>
<p class="mb-6">
	Log a weigh-in from the <strong>Weight</strong> page or the dashboard widget. The page shows your latest
	reading, a 7-day average, your 30-day change and weekly rate of change, a chart, and full history you
	can edit or delete from. If you've set a target weight and date on the Goals page, a projection shows
	whether your current rate gets you there in time.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Sleep</h2>
<p class="mb-6">
	Log a night from the <strong>Sleep</strong> page: pick the date, either a duration or a bedtime and
	wake time (Bissbilanz works out the duration for you), a quality rating and, optionally, wake-ups and
	notes. The page charts your trend and lists your history.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Supplements</h2>
<p class="mb-6">
	Create a supplement on the <strong>Supplements</strong> page with its schedule (daily, every other day,
	weekly or specific days) and reminder time, and it shows up as a checklist on the dashboard and its
	own page — tap to mark it taken for the day. Taking it also logs the nutrients it carries, if you gave
	it any.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Water</h2>
<p class="mb-6">
	Track water intake from the <strong>day properties</strong> card on any day's log — it shows progress
	toward your daily goal, which you can change in Settings. The same card also holds manual activity calories
	and a free-text note for the day.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Fasting</h2>
<p class="mb-6">
	Start a fast from the <strong>Fasting</strong> page with a target duration; it runs as a live
	timer until you end it, and the finished session is saved to your history with your average this
	week, your longest fast, and whether you reached your target. If a day has no entries because you
	fasted rather than forgot to log, mark it a <strong>Fasting Day</strong> from its day properties so
	it's counted as an intentional zero-calorie day in statistics and predictions instead of being treated
	as missing data.
</p>
