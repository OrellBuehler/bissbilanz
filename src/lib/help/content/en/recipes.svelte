<h2 class="mb-3 mt-8 text-xl font-semibold">Building a recipe</h2>
<p class="mb-6">
	On the <strong>Recipes</strong> page, tap the add button, give the recipe a name and add ingredients
	from your food database with a quantity and unit each. Set how many servings the whole recipe makes
	— Bissbilanz divides the combined calories and macros across them, so logging one serving later logs
	the right share automatically.
</p>
<p class="mb-6">
	Tap a recipe to edit its name, servings, photo or favorite status, or to delete it. To change the
	ingredients themselves, delete the recipe and rebuild it — there's no ingredient editor on an
	existing recipe yet.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Logging a recipe</h2>
<p class="mb-6">
	A recipe shows up in the <strong>Recipes</strong> tab of the add-entry sheet, and in Favorites if you've
	starred it. Logging it records one entry for the number of servings you choose — the calories and macros
	for that many servings are calculated automatically.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Recipe suggestions</h2>
<p class="mb-6">
	The <strong>Recipe suggestions</strong> page (and dashboard widget) looks at what you've already logged
	today, your remaining calorie and macro budget, and every recipe you've built, and ranks them by how
	well a serving would fit what's left. It's a fast way to decide what to cook next without doing the
	math yourself.
</p>
