<h2 class="mb-3 mt-8 text-xl font-semibold">Lege deine täglichen Ziele fest</h2>
<p class="mb-6">
	Öffne <strong>Ziele</strong> und lege dein tägliches Kalorienziel fest, danach Protein, Kohlenhydrate
	und Fett (Ballaststoffe folgen automatisch). Damit werden dein Dashboard und dein Verlauf jeden Tag
	verglichen. Du kannst sie jederzeit ändern — es gibt keine Bindung.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Erfasse deine erste Mahlzeit</h2>
<p class="mb-6">
	Auf dem <strong>Übersicht</strong>-Dashboard hat jeder Mahlzeitenbereich (standardmässig
	Frühstück, Mittagessen, Abendessen, Snacks) eine Schaltfläche <strong>Hinzufügen</strong>. Sie
	öffnet eine Suche in deiner Lebensmitteldatenbank sowie Tabs für Favoriten, zuletzt erfasste
	Lebensmittel, Rezepte und einen Schnelleintrag für Dinge, die du nicht als Lebensmittel speichern
	willst. Tippe auf ein Ergebnis, lege die Portionen fest, und es ist erfasst.
</p>
<p class="mb-6">
	Noch nichts in deiner Lebensmitteldatenbank? Scanne auf demselben Bildschirm einen Barcode oder
	durchsuche Open Food Facts — Details dazu in der Anleitung zum Scannen.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Gestalte das Dashboard nach deinen Wünschen</h2>
<p class="mb-6">
	In den <strong>Einstellungen</strong> listet die Karte <strong>Dashboard-Bereiche</strong> jedes Widget
	auf, das die Übersicht anzeigen kann — das Tagesprotokoll, das Diagramm, Favoriten, Rezeptvorschläge,
	Supplemente, Gewicht, Schlaf, Mahlzeiten- und Top-Lebensmittel-Übersichten, Fasten sowie Tageseigenschaften
	(Wasser, Aktivitätskalorien, Notizen). Schalte einzelne davon aus und ziehe die verbleibenden per Griff
	in die gewünschte Reihenfolge.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Orientierung in der App</h2>
<p class="mb-3">
	Die Seitenleiste (oder die untere Leiste auf dem Smartphone) ist nach Tätigkeit gruppiert:
</p>
<ul class="mb-6 list-disc space-y-1 pl-6">
	<li><strong>Übersicht, Favoriten, Verlauf</strong> — tägliches Erfassen.</li>
	<li>
		<strong>Lebensmittel, Rezepte, Rezeptvorschläge, Supplemente, Fasten, KI-Aufgaben</strong> — verwalten,
		was du erfassen kannst.
	</li>
	<li><strong>Einblicke, Ziele, Gewicht, Schlaf, Erhaltung</strong> — Trends überprüfen.</li>
	<li><strong>Hilfe, Einstellungen</strong> — dieses Hilfe-Center und App-Einstellungen.</li>
</ul>
