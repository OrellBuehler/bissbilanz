<h2 class="mb-3 mt-8 text-xl font-semibold">Ein Rezept erstellen</h2>
<p class="mb-6">
	Tippe auf der Seite <strong>Rezepte</strong> auf die Schaltfläche zum Hinzufügen, gib dem Rezept einen
	Namen und füge Zutaten aus deiner Lebensmitteldatenbank mit jeweils einer Menge und Einheit hinzu. Lege
	fest, wie viele Portionen das ganze Rezept ergibt — Bissbilanz teilt die zusammengezählten Kalorien
	und Makros darauf auf, sodass das spätere Erfassen einer Portion automatisch den richtigen Anteil erfasst.
</p>
<p class="mb-6">
	Tippe auf ein Rezept, um Name, Portionenanzahl, Foto oder Favoritenstatus zu bearbeiten oder es zu
	löschen. Um die Zutaten selbst zu ändern, lösche das Rezept und baue es neu auf — für ein
	bestehendes Rezept gibt es noch keinen Zutaten-Editor.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Ein Rezept erfassen</h2>
<p class="mb-6">
	Ein Rezept erscheint im Tab <strong>Rezepte</strong> des Erfassungsblatts sowie in den Favoriten, wenn
	du es mit einem Stern markiert hast. Beim Erfassen wird ein Eintrag für die gewählte Anzahl Portionen
	angelegt — die Kalorien und Makros für diese Menge werden automatisch berechnet.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Rezeptvorschläge</h2>
<p class="mb-6">
	Die Seite <strong>Rezeptvorschläge</strong> (und das gleichnamige Dashboard-Widget) betrachtet, was
	du heute bereits erfasst hast, dein verbleibendes Kalorien- und Makrobudget sowie jedes von dir erstellte
	Rezept, und ordnet sie danach, wie gut eine Portion zum Rest passen würde. So entscheidest du schnell,
	was als Nächstes zubereitet wird, ohne selbst zu rechnen.
</p>
