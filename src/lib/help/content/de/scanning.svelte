<h2 class="mb-3 mt-8 text-xl font-semibold">Barcode scannen</h2>
<p class="mb-6">
	Tippe auf die Scan-Schaltfläche im Dashboard oder auf <strong>Scannen</strong> bei einem Tag im Verlauf,
	um die Kamera zu öffnen. Richte sie auf den Barcode eines verpackten Produkts — ist es bereits in deiner
	Lebensmitteldatenbank, kannst du es direkt erfassen; andernfalls sucht Bissbilanz es bei Open Food Facts
	und füllt ein neues Lebensmittel mit Name, Portionsgrösse und Nährwerten vor, die du prüfen und speichern
	kannst.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Nährwertetikett scannen</h2>
<p class="mb-6">
	Nutze beim Hinzufügen oder Bearbeiten eines Lebensmittels <strong>Etikett scannen</strong>, um die
	Nährwerttabelle auf der Verpackung zu fotografieren, statt jede Zahl von Hand einzutippen. Der
	Scan läuft vollständig auf deinem Gerät — es wird nichts hochgeladen — und überträgt Kalorien,
	Makros und die erkannten erweiterten Nährstoffe ins Formular, wo du sie vor dem Speichern prüfen
	und korrigieren kannst.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Open Food Facts durchsuchen</h2>
<p class="mb-6">
	Kein Barcode zum Scannen oder das Produkt ist nicht verpackt? Suche danach auf der Seite
	<strong>Lebensmittel</strong> — finden sich weniger als eine Handvoll eigener Lebensmittel, erscheinen
	darunter Ergebnisse von Open Food Facts. Tippe auf eines, um ein neues Lebensmittel genauso vorauszufüllen
	wie beim Barcode-Scan.
</p>
<p class="mb-6">
	In beiden Fällen landen die gespeicherten Werte als Kopie in <em>deiner</em>
	Lebensmitteldatenbank — im Abschnitt
	<a href="/help/food-database" class="underline">Deine Lebensmitteldatenbank</a> erfährst du, warum,
	und wie du einen falschen Wert korrigierst.
</p>
