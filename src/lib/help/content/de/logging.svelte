<h2 class="mb-3 mt-8 text-xl font-semibold">Einen Eintrag hinzufügen</h2>
<p class="mb-6">
	Tippe bei einem Mahlzeitenbereich auf <strong>Hinzufügen</strong>, um das Erfassungsblatt zu
	öffnen. Es hat fünf Tabs:
</p>
<ul class="mb-6 list-disc space-y-1 pl-6">
	<li><strong>Suche</strong> — deine eigene Lebensmitteldatenbank, nach Name, Label oder Marke.</li>
	<li>
		<strong>Favoriten</strong> — mit Stern markierte Lebensmittel und Rezepte, ein Tipp genügt.
	</li>
	<li><strong>Zuletzt verwendet</strong> — was du zuletzt erfasst hast.</li>
	<li><strong>Rezepte</strong> — jedes von dir erstellte Rezept.</li>
	<li>
		<strong>Schnelleintrag</strong> — für etwas, das du nicht als Lebensmittel speichern willst, wie ein
		Restaurantessen. Gib Kalorien und Makros direkt ein (oder nur einen Namen und eine Schätzung), und
		es wird erfasst, ohne ein Lebensmittel anzulegen.
	</li>
</ul>
<p class="mb-6">
	Unabhängig vom gewählten Tab kannst du die Anzahl Portionen festlegen und oben im Blatt die
	Uhrzeit anpassen, bevor du bestätigst.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Einträge bearbeiten und löschen</h2>
<p class="mb-6">
	Tippe auf einen erfassten Eintrag, um Portionen, Mahlzeit, Datum oder Uhrzeit zu ändern oder ihn
	zu löschen. Wenn du einen Eintrag auf einen anderen Tag verschiebst, erscheint eine
	<strong>Rückgängig</strong>-Option, falls du versehentlich den falschen Tag gewählt hast.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Einen vergangenen Tag kopieren</h2>
<p class="mb-6">
	Isst du wieder dasselbe wie vor ein paar Tagen? Öffne diesen Tag im <strong>Verlauf</strong>,
	nutze <strong>Von einem anderen Tag kopieren</strong> und wähle das Quelldatum — jeder Eintrag dieses
	Tages wird zum angezeigten Tag hinzugefügt (nichts wird überschrieben, es ist also sicher, es auch bei
	einem Tag mit bereits vorhandenen Einträgen zu nutzen).
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Favoriten</h2>
<p class="mb-6">
	Markiere ein Lebensmittel oder Rezept mit einem Stern, um es zu <strong>Favoriten</strong>
	hinzuzufügen — das erscheint auch als Dashboard-Widget zum Erfassen mit einem Tipp. In den Einstellungen
	kannst du festlegen, ob ein Favorit anhand der Tageszeit einer Mahlzeit zugeordnet wird oder dich jedes
	Mal danach fragt.
</p>
