<h2 class="mb-3 mt-8 text-xl font-semibold">Gewicht</h2>
<p class="mb-6">
	Erfasse eine Messung auf der Seite <strong>Gewicht</strong> oder im Dashboard-Widget. Die Seite zeigt
	deinen letzten Wert, einen 7-Tage-Durchschnitt, deine Veränderung über 30 Tage und die wöchentliche
	Veränderungsrate, ein Diagramm sowie den vollständigen Verlauf, den du bearbeiten oder löschen kannst.
	Hast du auf der Seite Ziele ein Zielgewicht mit Datum festgelegt, zeigt eine Prognose, ob du mit deiner
	aktuellen Rate rechtzeitig ankommst.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Schlaf</h2>
<p class="mb-6">
	Erfasse eine Nacht auf der Seite <strong>Schlaf</strong>: Wähle das Datum, entweder eine Dauer
	oder eine Bettzeit und Aufwachzeit (Bissbilanz berechnet die Dauer für dich), eine Qualitätsangabe
	und optional Aufwachvorgänge und Notizen. Die Seite zeigt deinen Trend als Diagramm und listet
	deinen Verlauf.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Supplemente</h2>
<p class="mb-6">
	Lege auf der Seite <strong>Supplemente</strong> ein Supplement mit Zeitplan (täglich, jeden zweiten
	Tag, wöchentlich oder an bestimmten Tagen) und Erinnerungszeit an — es erscheint dann als Checkliste
	im Dashboard und auf seiner eigenen Seite. Tippe, um es für den Tag als eingenommen zu markieren. Das
	Einnehmen erfasst gleichzeitig die enthaltenen Nährstoffe, falls du welche angegeben hast.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Wasser</h2>
<p class="mb-6">
	Erfasse deine Wasseraufnahme über die Karte <strong>Tageseigenschaften</strong> im Protokoll eines beliebigen
	Tages — sie zeigt den Fortschritt zu deinem täglichen Ziel, das du in den Einstellungen ändern kannst.
	Dieselbe Karte enthält auch manuelle Aktivitätskalorien und eine freie Notiz für den Tag.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Fasten</h2>
<p class="mb-6">
	Starte ein Fasten auf der Seite <strong>Fasten</strong> mit einer Zieldauer; es läuft als Live-
	Timer, bis du es beendest, und die abgeschlossene Session wird mit deinem Durchschnitt dieser
	Woche, deinem längsten Fasten und ob du dein Ziel erreicht hast in deinem Verlauf gespeichert. Hat
	ein Tag keine Einträge, weil du gefastet statt vergessen hast zu erfassen, markiere ihn in seinen
	Tageseigenschaften als <strong>Fastentag</strong>, damit er in Statistiken und Prognosen als
	bewusster Null-Kalorien-Tag gezählt wird statt als fehlende Daten.
</p>
