<h2 class="mb-3 mt-8 text-xl font-semibold">Drei Tabs</h2>
<p class="mb-6">
	Die Seite <strong>Einblicke</strong> ist in <strong>Ernährung</strong>, <strong>Gewicht</strong>
	und <strong>Schlaf</strong> unterteilt. Ernährung umfasst Trends, Zieltreue, eine Kalender-Heatmap,
	deine Erfassungsserie, ein Makro-Radar und Muster nach Wochentag sowie eine Reihe tiefergehender Analysekarten
	(Nährstoff-Timing, Lebensmittelvielfalt, Mahlzeitenregelmässigkeit und mehr), die du einzeln aufklappen
	kannst. Die Tabs Gewicht und Schlaf spiegeln die Seiten Gewicht und Schlaf, sodass du beides an derselben
	Stelle einsehen kannst.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">An das Dashboard anheften</h2>
<p class="mb-6">
	Eine Analysekarte gefunden, die du oft prüfst? Tippe auf ihre Pin-Schaltfläche, um sie zu deinem
	<strong>Übersicht</strong>-Dashboard hinzuzufügen, sodass sie dort erscheint, ohne dass du jedes
	Mal die Einblicke öffnen musst. Du kannst bis zu sechs gleichzeitig anheften — löse eine entweder
	von der Karte oder vom Dashboard, um Platz für eine andere zu schaffen.
</p>

<h2 class="mb-3 mt-8 text-xl font-semibold">Eine Karte lesen</h2>
<p class="mb-6">
	Die meisten Karten brauchen eine gewisse Regelmässigkeit beim Erfassen (und bei den Gewichts- und
	Schlafkarten regelmässige Messungen bzw. Schlafeinträge), bevor sie etwas Aussagekräftiges zeigen
	— eine dünne Karte mit nur ein oder zwei Tagen dahinter ist Rauschen, kein Muster. Gib ihr ein
	paar Wochen, bevor du Schlüsse daraus ziehst.
</p>
