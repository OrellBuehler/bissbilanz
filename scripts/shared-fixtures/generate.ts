/**
 * Generates the broad cross-platform fixtures in tests/fixtures/shared/generated-*.json
 * by running the TypeScript implementations (the server is the source of truth).
 *
 *   bun run shared:generate   rewrite the files
 *   bun run shared:check      fail when a file is stale (CI)
 *
 * The hand-written fixtures next to them (recipe-math.json, goal-rules.json, ...) pin
 * individual reviewed cases; these grids sweep the input space so a platform that
 * rounds, converts or orders differently fails on a case nobody thought to write.
 * See tests/fixtures/shared/README.md.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

import { runGeneratedCase } from '../../tests/shared-fixtures/runners';
import { servingUnitValues } from '../../src/lib/units';

type Platform = 'web' | 'kotlin' | 'swift';
type Divergence = { platform: Platform; expected: unknown; reason: string };
type Case = {
	fn: string;
	name: string;
	input: Record<string, unknown>;
	expected: unknown;
	divergences?: Divergence[];
};
type FixtureFile = {
	$comment: string;
	tolerance: number;
	implementations: Record<string, Platform[]>;
	cases: Case[];
};

const ALL: Platform[] = ['web', 'kotlin', 'swift'];
const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../tests/fixtures/shared');

const make = (fn: string, name: string, input: Record<string, unknown>): Case => ({
	fn,
	name,
	input,
	expected: runGeneratedCase(fn, input)
});

// --- unit conversion ---------------------------------------------------------

function unitConversion(): FixtureFile {
	const cases: Case[] = [];
	for (const from of servingUnitValues) {
		for (const to of servingUnitValues) {
			for (const quantity of [0.5, 1, 250]) {
				cases.push(
					make('convertQuantityForMacros', `${from}_to_${to}_x${quantity}`, { quantity, from, to })
				);
			}
		}
	}
	return {
		$comment:
			'Generated by scripts/shared-fixtures/generate.ts from src/lib/units.ts: every serving unit converted to every other (cross-dimension pairs fall back to the raw quantity).',
		tolerance: 1e-9,
		implementations: { convertQuantityForMacros: ALL },
		cases
	};
}

